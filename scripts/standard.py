try:
    import yaml
except ImportError:
    sys.exit("PyYAML is required. Install it with: pip install pyyaml")

STANDARD_ROOT = Path(__file__).resolve().parent.parent
BASE = STANDARD_ROOT / "base"
PROFILES = STANDARD_ROOT / "profiles"

DEFAULT_REPO = "SVN11X/standards"
DEFAULT_OWNER = "SVN11X"
OWNER_TODO = "TODO(owner)"
LANGUAGES = {"en": "English", "es": "Spanish", "pt": "Portuguese", "fr": "French", "de": "German", "it": "Italian"}
CONFIG_KEYS = ["standard", "owner", "name", "profile", "setup", "license", "content_language",
               "github", "options", "parts", "part_options", "extra_folders", "skills"]

PLACEHOLDER = re.compile(r"(?<!\$)\{\{([a-z_]+)\}\}")
STANDARD_REF = re.compile(r"^(?P<repo>[\w.-]+/[\w.-]+)@(?P<ref>v\d+(?:\.\d+){0,2})$")
GENERATED_VERSION = re.compile(r"<!-- Generated by \S+ (?P<version>\d+\.\d+\.\d+) ")
MARKED_BLOCK = re.compile(r"<!-- (?P<name>[\w-]+):start -->.*?<!-- (?P=name):end -->\n?", re.S)
CONVENTIONAL_TITLE = re.compile(r"^(feat|fix|docs|style|refactor|perf|test|build|ci|chore|revert)(\([\w./-]+\))?!?: \S")
TODO_MARK = re.compile(r"\b(TODO|FIXME)\b(?!\(owner\))")
ISSUE_REF = re.compile(r"#\d+|https?://")
PR_SECTIONS = ["Task", "What I understood", "Assumptions", "Decisions", "Not done", "How to verify"]
TEXT_SUFFIXES = {".md", ".txt", ".html", ".htm", ".css", ".scss", ".js", ".mjs", ".jsx", ".ts", ".tsx",
                 ".vue", ".svelte", ".py", ".c", ".h", ".cpp", ".hpp", ".rs", ".go", ".java", ".tex", ".typ"}
GENERATED_FILES = {"AGENTS.md", "CLAUDE.md"}


class StandardError(Exception):
    """A problem the user can fix. Reported without a traceback."""


# Files

def write_text(path: Path, text: str) -> None:
    """Write UTF-8 with LF line endings on every system, as .gitattributes expects."""
    with path.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)


# Loading

def load_yaml(path: Path) -> dict:
    with path.open(encoding="utf-8") as handle:
        return yaml.safe_load(handle) or {}


def base_config() -> dict:
    return load_yaml(BASE / "base.yml")


def profile_names() -> list[str]:
    return sorted(p.name for p in PROFILES.iterdir() if (p / "profile.yml").exists())


def load_profile(name: str) -> dict:
    path = PROFILES / str(name) / "profile.yml"
    if not path.exists():
        raise StandardError(f"Unknown profile '{name}'. Profiles: {', '.join(profile_names())}")
    profile = load_yaml(path)
    profile["_dir"] = path.parent
    return profile


def as_text(value) -> str:
    # YAML 1.1 reads yes, no, on and off as booleans. Options are always text.
    if isinstance(value, bool):
        return "yes" if value else "no"
    return str(value)


def parse_standard(value) -> tuple[str, str]:
    match = STANDARD_REF.match(str(value or ""))
    if not match:
        raise StandardError(f"'standard' must look like OWNER/REPO@v1, got '{value}'")
    return match["repo"], match["ref"]


def read_config(repo: Path) -> dict:
    path = repo / ".standard.yml"
    if not path.exists():
        raise StandardError(f"{path} not found. Run init first.")
    return load_yaml(path)


def write_config(repo: Path, config: dict) -> None:
    ordered = {key: config[key] for key in CONFIG_KEYS if key in config}
    header = ("# Identity of this repository for the standard.\n"
              "# After editing, run: python .standards/scripts/standard.py agents .\n")
    body = yaml.safe_dump(ordered, sort_keys=False, allow_unicode=True, width=120)
    write_text(repo / ".standard.yml", header + body)


def resolve(profile: dict, answers: dict) -> dict:
    """Combine a profile with the owner's answers into folders, rules and files."""
    folders = {name: dict(spec or {}) for name, spec in (profile.get("folders") or {}).items()}
    subfolders: dict[str, dict] = {}
    files = list(profile.get("files") or [])
    root_files = list(profile.get("root_files") or [])
    topics = list(profile.get("topics") or [])
    option_rules: list[str] = []
    problems: list[str] = []
    options = profile.get("options") or {}
    for key, spec in options.items():
        value = as_text(answers.get(key, spec.get("default")))
        if spec.get("free"):
            continue
        choices = spec.get("choices") or {}
        if value not in choices:
            problems.append(f"Option {key}={value} is not valid. Choices: {', '.join(choices)}")
            continue
        choice = choices[value] or {}
        option_rules.extend(f"{key} = {value}: {rule}" for rule in choice.get("rules") or [])
        for name, spec_folder in (choice.get("add_folders") or {}).items():
            folders[name] = dict(spec_folder)
        for name in choice.get("remove_folders") or []:
            folders.pop(name, None)
        for parent, children in (choice.get("subfolders") or {}).items():
            subfolders.setdefault(parent, {}).update(children)
        files.extend(choice.get("files") or [])
        root_files.extend(choice.get("root_files") or [])
        topics.extend(choice.get("topics") or [])
    for key in sorted(set(answers) - set(options)):
        problems.append(f"Option '{key}' does not exist in the {profile['name']} profile.")
    subfolders = {parent: children for parent, children in subfolders.items() if parent in folders}
    return {"folders": folders, "subfolders": subfolders, "files": files, "root_files": root_files,
            "topics": list(dict.fromkeys(topics)), "option_rules": option_rules, "problems": problems}


# Rendering

def render(text: str, context: dict) -> str:
    def replace(match: re.Match) -> str:
        key = match.group(1)
        if key not in context:
            raise StandardError(f"Template placeholder '{key}' has no value")
        return str(context[key])
    return PLACEHOLDER.sub(replace, text)


def tidy(text: str) -> str:
    text = re.sub(r"\n{3,}", "\n\n", text)
    return "\n".join(line.rstrip() for line in text.splitlines()).strip() + "\n"


def bullets(items) -> str:
    return "\n".join(f"- {item}" for item in items)


def markdown_sections(text: str) -> dict[str, str]:
    text = re.sub(r"<!--.*?-->", "", text, flags=re.S)
    sections: dict[str, list[str]] = {}
    current = None
    for line in text.splitlines():
        heading = re.match(r"^##\s+(.+?)\s*$", line)
        if heading:
            current = heading.group(1)
            sections[current] = []
        elif current is not None:
            sections[current].append(line)
    return {title: "\n".join(lines).strip() for title, lines in sections.items()}


def layout_lines(folders: dict, subfolders: dict, parts: dict, extra: dict, with_docs: bool) -> list[str]:
    lines = []
    for name, spec in folders.items():
        line = f"- `{name}/`: {spec.get('description', '')}" + (" Optional." if spec.get("optional") else "")
        children = subfolders.get(name)
        if children:
            line += " Inside: " + ", ".join(f"`{child}/`" for child in children) + "."
        if spec.get("license"):
            line += f" Own license: {spec['license']} in `{name}/LICENSE`."
        lines.append(line)
    if with_docs:
        lines.append("- `docs/`: goals, glossary, assumptions, decisions and specs.")
    for part, part_profile in parts.items():
        lines.append(f"- `{part}/`: part with the {part_profile} profile. Read `{part}/AGENTS.md` before working there.")
    for name, reason in extra.items():
        lines.append(f"- `{name}/`: extra folder declared in .standard.yml. {reason}")
    return lines


def goal_summary(repo: Path) -> list[str]:
    path = repo / "docs" / "goals.md"
    sections = markdown_sections(path.read_text(encoding="utf-8")) if path.exists() else {}
    picks = [("Vision", 1), ("Non-goals", 3), ("Priorities", 3)]
    lines, missing = [], []
    for title, limit in picks:
        content = [line.strip() for line in sections.get(title, "").splitlines() if line.strip()]
        if not content or any(OWNER_TODO in line for line in content):
            missing.append(title)
            continue
        items = [line.lstrip("-*0123456789. ").strip() for line in content[:limit]]
        lines.append(f"- {title}: " + " ".join(items))
    if len(missing) == len(picks):
        return ["- docs/goals.md is not written yet. Before any product decision (what to build, "
                "for whom, which trade-off), ask the owner."]
    lines.extend(f"- {title}: not written yet. Ask the owner before decisions that depend on it."
                 for title in missing)
    lines.append("- Full text: docs/goals.md. Read it before planning.")
    return lines


def core_preferences() -> list[str]:
    path = STANDARD_ROOT / "preferences.md"
    if not path.exists():
        return []
    found = []
    for line in path.read_text(encoding="utf-8").splitlines():
        match = re.match(r"^- \[core\]\s+(.*)$", line.strip())
        if match:
            found.append(f"- {match.group(1)}")
    return found[:5]


def content_language_rule(profile_name: str, code: str) -> str:
    language = LANGUAGES.get(code, code)
    if code == "en":
        return "User-facing content is in English."
    if profile_name == "docs":
        return f"The document text in content/ is written in {language}. Everything else stays in English."
    return (f"User-facing content is in {language}. Keep it in content or locale files "
            f"(for example locales/{code}.json), separate from code.")


def common_context(repo: Path, config: dict) -> dict:
    standard_repo, ref = parse_standard(config.get("standard"))
    profile = load_profile(config.get("profile"))
    resolved = resolve(profile, config.get("options") or {})
    if resolved["problems"]:
        raise StandardError(" ".join(resolved["problems"]))
    parts = config.get("parts") or {}
    license_key = str(config.get("license", "none"))
    options = config.get("options") or {}
    built = options.get("build") == "npm"
    return {
        "profile_data": profile,
        "resolved": resolved,
        "standard_repo": standard_repo,
        "ref": ref,
        "version": base_config()["version"],
        "standard": config["standard"],
        "name": config.get("name") or repo.name,
        "owner": config.get("owner") or DEFAULT_OWNER,
        "profile": profile["name"],
        "license": license_key,
        "license_line": ("Not licensed for reuse. All rights reserved." if license_key.lower() == "none"
                         else f"{license_key}. See LICENSE."),
        "layout_lines": "\n".join(layout_lines(resolved["folders"], resolved["subfolders"], parts,
                                               config.get("extra_folders") or {}, with_docs=True)),
        "site_dir": "dist" if built else "src",
        "build_steps": ("\n      - uses: actions/setup-node@v5\n        with:\n          node-version: 22\n"
                        "          cache: npm\n      - run: npm ci\n      - run: npm run build") if built else "",
    }


def build_instruction_files(repo: Path, config: dict) -> dict[str, str]:
    """Return every generated instruction file, keyed by its path relative to the repository."""
    base = base_config()
    ctx = common_context(repo, config)
    profile, resolved = ctx["profile_data"], ctx["resolved"]
    parts = config.get("parts") or {}
    pending = config.get("setup") != "done"
    agents_ctx = dict(ctx)
    agents_ctx.update({
        "profile_description": profile["description"].rstrip("."),
        "setup": ("done" if not pending else
                  "pending. The options below are defaults the owner has not confirmed. "
                  "Ask before decisions that depend on them"),
        "parts_lines": "\n".join(f"- Part `{p}/` follows the {pp} profile. Read `{p}/AGENTS.md` before working there."
                                 for p, pp in parts.items()),
        "goal_summary": "\n".join(goal_summary(repo)),
        "content_language_rule": content_language_rule(profile["name"], str(config.get("content_language", "en"))),
        "fixed_rules": bullets(list(base["fixed"]) + list(profile.get("fixed") or [])),
        "option_rules": bullets(resolved["option_rules"]) or "- None.",
        "with_reason": bullets(profile.get("with_reason") or []) or "- Nothing listed for this profile.",
        "patterns": ", ".join(profile.get("patterns") or []) or "none listed for this profile",
        "anti_slop": bullets(base["anti_slop"]),
        "preferences": "\n".join(core_preferences()) or "- None recorded.",
        "skills": ", ".join(config.get("skills") or []) or "none",
        "skills_repo": ctx["standard_repo"].split("/")[0] + "/skills",
    })
    files = {
        "AGENTS.md": tidy(render((BASE / "agents.md.tmpl").read_text(encoding="utf-8"), agents_ctx)),
        "CLAUDE.md": "@AGENTS.md\n",
    }
    part_template = (BASE / "part-agents.md.tmpl").read_text(encoding="utf-8")
    for part, part_profile_name in parts.items():
        part_profile = load_profile(part_profile_name)
        part_resolved = resolve(part_profile, (config.get("part_options") or {}).get(part) or {})
        if part_resolved["problems"]:
            raise StandardError(f"Part {part}: " + " ".join(part_resolved["problems"]))
        part_ctx = {
            "standard_repo": ctx["standard_repo"],
            "ref": ctx["ref"],
            "version": ctx["version"],
            "part": part,
            "profile": part_profile["name"],
            "profile_description": part_profile["description"].rstrip("."),
            "layout_lines": "\n".join(layout_lines(part_resolved["folders"], part_resolved["subfolders"],
                                                   {}, {}, with_docs=False)),
            "fixed_rules": bullets(part_profile.get("fixed") or []),
            "option_rules": bullets(part_resolved["option_rules"]) or "- None.",
            "with_reason": bullets(part_profile.get("with_reason") or []) or "- Nothing listed for this profile.",
            "patterns": ", ".join(part_profile.get("patterns") or []) or "None listed",
        }
        files[f"{part}/AGENTS.md"] = tidy(render(part_template, part_ctx))
        files[f"{part}/CLAUDE.md"] = "@AGENTS.md\n"
    return files


def keep_marked_blocks(new_text: str, old_text: str) -> str:
    """Carry over blocks that other installers own, such as an antislop pointer block."""
    blocks = [m.group(0).rstrip("\n") for m in MARKED_BLOCK.finditer(old_text) if m["name"] != "skills"]
    if not blocks:
        return new_text
    return new_text.rstrip("\n") + "\n\n" + "\n\n".join(blocks) + "\n"


def without_marked_blocks(text: str) -> str:
    return MARKED_BLOCK.sub(lambda m: m.group(0) if m["name"] == "skills" else "", text)


def comparable(text: str) -> str:
    """Generated text without other installers' blocks and without the header that names the version."""
    lines = tidy(without_marked_blocks(text)).splitlines()
    return "\n".join(line for line in lines if not GENERATED_VERSION.match(line))


def write_instruction_files(repo: Path, config: dict) -> list[str]:
    written = []
    for rel, content in build_instruction_files(repo, config).items():
        path = repo / rel
        old = path.read_text(encoding="utf-8") if path.exists() else ""
        new = keep_marked_blocks(content, old)
        if new != old:
            path.parent.mkdir(parents=True, exist_ok=True)
            write_text(path, new)
            written.append(rel)
    return written


# init

def folder_readme(name: str, spec: dict) -> str:
    lines = [f"# {name}", "", spec.get("description", ""), ""]
    for label, key in (("Goes here", "goes_here"), ("Does not go here", "not_here"), ("Naming", "naming")):
        if spec.get(key):
            lines.append(f"- {label}: {spec[key]}")
    return "\n".join(lines).strip() + "\n"


def write_if_missing(path: Path, content: str, created: list[str], repo: Path) -> None:
    if path.exists():
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    write_text(path, content)
    created.append(path.relative_to(repo).as_posix())


def merge_gitignore(path: Path, lines: list[str]) -> bool:
    existing = path.read_text(encoding="utf-8").splitlines() if path.exists() else []
    missing = [line for line in lines if line not in existing]
    if not missing:
        return False
    block = ([""] if existing else []) + ["# standard"] + missing
    write_text(path, "\n".join(existing + block) + "\n")
    return True


def license_text(key: str, owner: str) -> str | None:
    if key.lower() == "none":
        return None
    path = BASE / "licenses" / f"{key.lower()}.txt"
    if not path.exists():
        available = ", ".join(sorted(p.stem for p in (BASE / "licenses").glob("*.txt")))
        raise StandardError(f"No license text for '{key}'. Available: {available}, none")
    return (path.read_text(encoding="utf-8")
            .replace("[year]", str(dt.date.today().year))
            .replace("[fullname]", owner))


def copy_tree(source: Path, repo: Path, ctx: dict, created: list[str]) -> None:
    for path in sorted(source.rglob("*")):
        if path.is_file():
            copy_file(path, path.relative_to(source).as_posix(), repo, ctx, created)


def copy_file(path: Path, rel: str, repo: Path, ctx: dict, created: list[str]) -> None:
    text = path.read_text(encoding="utf-8")
    if rel.endswith(".tmpl"):
        rel = rel[: -len(".tmpl")]
        text = render(text, ctx)
    write_if_missing(repo / rel, text, created, repo)


def parse_pairs(values) -> dict:
    pairs = {}
    for item in values or []:
        key, sep, value = item.partition("=")
        if not sep or not key:
            raise StandardError(f"Expected KEY=VALUE, got '{item}'")
        pairs[key.strip()] = value.strip()
    return pairs


def ask(question: str, choices, default: str) -> str:
    hint = f" ({' | '.join(choices)})" if choices else ""
    while True:
        value = input(f"{question}{hint} [{default}]: ").strip() or default
        if not choices or value in choices:
            return value
        print("Choose one of: " + ", ".join(choices))


def ask_options(profile: dict, answers: dict) -> dict:
    for key, spec in (profile.get("options") or {}).items():
        default = as_text(answers.get(key, spec.get("default")))
        choices = None if spec.get("free") else list(spec.get("choices") or {})
        answers[key] = ask(spec["question"], choices, default)
    return answers


def build_config(repo: Path, config: dict, profile: dict, settings: dict) -> dict:
    answers = {k: as_text(v) for k, v in (config.get("options") or {}).items()}
    answers.update(settings.get("options") or {})
    if settings.get("interactive"):
        answers = ask_options(profile, answers)
    options = {key: as_text(answers.get(key, spec.get("default")))
               for key, spec in (profile.get("options") or {}).items()}
    for key, value in answers.items():
        options.setdefault(key, value)

    parts = dict(config.get("parts") or {})
    parts.update(settings.get("parts") or {})
    part_answers = {part: dict(values or {}) for part, values in (config.get("part_options") or {}).items()}
    for key, value in (settings.get("part_options") or {}).items():
        part, _, option = key.partition(".")
        part_answers.setdefault(part, {})[option] = value
    part_options = {}
    for part, part_profile_name in parts.items():
        part_profile = load_profile(part_profile_name)
        current = part_answers.get(part, {})
        part_options[part] = {key: as_text(current.get(key, spec.get("default")))
                              for key, spec in (part_profile.get("options") or {}).items()}

    major = base_config()["version"].split(".")[0]
    owner = settings.get("owner") or config.get("owner") or DEFAULT_OWNER
    name = settings.get("name") or config.get("name") or repo.name
    current = dict(config.get("github") or {})
    resolved_now = resolve(profile, options)
    homepage = current.get("homepage", "")
    if not homepage and options.get("hosting") == "github-pages" and name != "CHANGE-ME":
        homepage = f"https://{owner.lower()}.github.io/{name}/"
    github = {
        "description": settings.get("description") or current.get("description", ""),
        "homepage": homepage,
        "topics": list(dict.fromkeys(list(current.get("topics") or []) + resolved_now["topics"])),
    }
    if current.get("features"):
        github["features"] = current["features"]
    content_language = settings.get("content_language") or config.get("content_language")
    if not content_language and settings.get("interactive"):
        content_language = ask("Language of user-facing content (for example en, es)", None, "en")
    setup_done = settings.get("interactive") or settings.get("setup_done")
    return {
        "standard": settings.get("standard") or config.get("standard") or f"{DEFAULT_REPO}@v{major}",
        "owner": owner,
        "name": name,
        "profile": profile["name"],
        "setup": "done" if setup_done else config.get("setup", "pending"),
        "license": settings.get("license") or config.get("license") or profile.get("license", "MIT"),
        "content_language": content_language or "en",
        "github": github,
        "options": options,
        "parts": parts,
        "part_options": part_options,
        "extra_folders": config.get("extra_folders") or {},
        "skills": config.get("skills") or list(dict.fromkeys(
            list(base_config().get("skills") or []) + list(profile.get("skills") or []))),
    }


def init_repo(repo: Path, settings: dict) -> list[str]:
    """Create or complete a repository. Existing files are never overwritten."""
    repo = repo.resolve()
    repo.mkdir(parents=True, exist_ok=True)
    existing_config = (repo / ".standard.yml").exists()
    if existing_config and not settings.get("existing"):
        raise StandardError(f"{repo / '.standard.yml'} already exists. Use --existing to add missing files.")
    config = read_config(repo) if existing_config else {}
    profile_name = settings.get("profile") or config.get("profile")
    if not profile_name:
        raise StandardError("Choose a profile with --profile: " + ", ".join(profile_names()))
    profile = load_profile(profile_name)
    config = build_config(repo, config, profile, settings)
    resolved = resolve(profile, config["options"])
    if resolved["problems"]:
        raise StandardError(" ".join(resolved["problems"]))
    write_config(repo, config)

    created: list[str] = []
    ctx = common_context(repo, config)
    copy_tree(BASE / "files", repo, ctx, created)
    for rel in resolved["files"]:
        copy_file(profile["_dir"] / "files" / rel, rel, repo, ctx, created)
    for rel in profile.get("required_files") or []:
        optional = BASE / "optional" / rel
        if optional.exists():
            copy_file(optional, rel, repo, ctx, created)

    for name, spec in resolved["folders"].items():
        if spec.get("optional") and not (repo / name).exists():
            continue
        write_if_missing(repo / name / "README.md", folder_readme(name, spec), created, repo)
        for child, description in resolved["subfolders"].get(name, {}).items():
            write_if_missing(repo / name / child / "README.md", f"# {child}\n\n{description}\n", created, repo)
        if spec.get("license"):
            text = license_text(spec["license"], config["owner"])
            if text:
                write_if_missing(repo / name / "LICENSE", text, created, repo)

    for part, part_profile_name in config["parts"].items():
        part_profile = load_profile(part_profile_name)
        part_resolved = resolve(part_profile, config["part_options"].get(part, {}))
        write_if_missing(repo / part / "README.md", folder_readme(part, {
            "description": f"Part of {config['name']} that follows the {part_profile['name']} profile.",
            "goes_here": "Everything for this part, in the layout listed in its AGENTS.md.",
            "not_here": "Files of the main profile or of other parts.",
            "naming": "As in the part's profile.",
        }), created, repo)
        for name, spec in part_resolved["folders"].items():
            write_if_missing(repo / part / name / "README.md", folder_readme(name, spec), created, repo)
        part_license = part_profile.get("license", "MIT")
        if part_license.lower() != str(config["license"]).lower():
            text = license_text(part_license, config["owner"])
            if text:
                write_if_missing(repo / part / "LICENSE", text, created, repo)

    gitignore_lines = list(base_config()["gitignore"]) + list(profile.get("gitignore") or [])
    for part_profile_name in config["parts"].values():
        gitignore_lines += [line for line in load_profile(part_profile_name).get("gitignore") or []
                            if line not in gitignore_lines]
    if merge_gitignore(repo / ".gitignore", gitignore_lines):
        created.append(".gitignore")

    text = license_text(str(config["license"]), config["owner"])
    if text:
        write_if_missing(repo / "LICENSE", text, created, repo)

    created += write_instruction_files(repo, config)
    return created


