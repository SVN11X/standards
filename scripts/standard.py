class Report:
    def __init__(self) -> None:
        self.errors: list[tuple[str, str]] = []
        self.warnings: list[tuple[str, str]] = []

    def error(self, where: str, message: str) -> None:
        self.errors.append((where, message))

    def warn(self, where: str, message: str) -> None:
        self.warnings.append((where, message))

    def print(self) -> int:
        annotate = os.environ.get("GITHUB_ACTIONS") == "true"
        for kind, items in (("error", self.errors), ("warning", self.warnings)):
            for where, message in items:
                if annotate:
                    print(f"::{kind} file={where}::{message}")
                else:
                    print(f"{kind.upper():7} {where}: {message}")
        print(f"\n{len(self.errors)} errors, {len(self.warnings)} warnings")
        return 1 if self.errors else 0


def list_files(repo: Path) -> list[str]:
    try:
        output = subprocess.run(["git", "ls-files", "--cached", "--others", "--exclude-standard"],
                                cwd=repo, capture_output=True, text=True, check=True).stdout
        files = [line for line in output.splitlines() if line]
    except (OSError, subprocess.CalledProcessError):
        files = [p.relative_to(repo).as_posix() for p in repo.rglob("*")
                 if p.is_file() and ".git" not in p.relative_to(repo).parts]
    return sorted(f for f in files if not f.startswith(".standards/") and (repo / f).is_file())


def lfs_patterns(repo: Path) -> list[str]:
    path = repo / ".gitattributes"
    if not path.exists():
        return []
    return [line.split()[0] for line in path.read_text(encoding="utf-8").splitlines()
            if "filter=lfs" in line and not line.lstrip().startswith("#")]


def prose_lines(text: str):
    """Yield (number, line) for Markdown lines outside code blocks, with inline code removed."""
    in_fence = False
    for number, line in enumerate(text.splitlines(), start=1):
        if line.lstrip().startswith(("```", "~~~")):
            in_fence = not in_fence
            continue
        if not in_fence:
            yield number, re.sub(r"`[^`]*`", "", line)


def check_config(repo: Path, config: dict, report: Report) -> tuple[dict, dict] | None:
    try:
        parse_standard(config.get("standard"))
        profile = load_profile(config.get("profile"))
    except StandardError as error:
        report.error(".standard.yml", str(error))
        return None
    resolved = resolve(profile, config.get("options") or {})
    for problem in resolved["problems"]:
        report.error(".standard.yml", problem)
    for part, part_profile_name in (config.get("parts") or {}).items():
        try:
            part_profile = load_profile(part_profile_name)
        except StandardError as error:
            report.error(".standard.yml", f"Part {part}: {error}")
            continue
        for problem in resolve(part_profile, (config.get("part_options") or {}).get(part) or {})["problems"]:
            report.error(".standard.yml", f"Part {part}: {problem}")
    if config.get("setup") != "done":
        report.warn(".standard.yml", "Setup is pending. Answer the setup questions and set setup: done.")
    if config.get("name") in (None, "", "CHANGE-ME"):
        report.warn(".standard.yml", "Set the repository name, then run agents.")
    return profile, resolved


def check_layout(files: list[str], config: dict, profile: dict, resolved: dict, report: Report) -> None:
    base = base_config()
    folders, subfolders = resolved["folders"], resolved["subfolders"]
    parts = config.get("parts") or {}
    extra = config.get("extra_folders") or {}
    declared = set(folders) | set(parts) | set(extra) | {"docs"}
    present = {f.split("/", 1)[0] for f in files if "/" in f}
    for name in sorted(present):
        if name.startswith("."):
            continue
        if name not in declared:
            report.error(name, "Top-level folder is not declared. Move its files into the layout, "
                               "or declare it in .standard.yml under extra_folders with a reason.")
        elif f"{name}/README.md" not in files:
            report.error(name, "Folder has no README.md.")
    for parent, children in subfolders.items():
        for child in children:
            if any(f.startswith(f"{parent}/{child}/") for f in files) and f"{parent}/{child}/README.md" not in files:
                report.warn(f"{parent}/{child}", "Folder has no README.md.")
    for part in parts:
        for required in ("AGENTS.md", "CLAUDE.md", "README.md"):
            if f"{part}/{required}" not in files:
                report.error(f"{part}/{required}", "Missing in a declared part. Run init --existing, then agents.")

    for name, spec in folders.items():
        allowed = {ext.lower() for ext in spec.get("extensions") or []}
        pattern = re.compile(spec["naming_regex"]) if spec.get("naming_regex") else None
        for rel in (f for f in files if f.startswith(f"{name}/")):
            filename = rel.rsplit("/", 1)[-1]
            if filename in ("README.md", "LICENSE", ".gitkeep"):
                continue
            suffix = filename.rsplit(".", 1)[-1].lower() if "." in filename else ""
            if allowed and suffix not in allowed:
                report.error(rel, f"File type .{suffix} does not belong in {name}/. Allowed: {', '.join(sorted(allowed))}.")
            if pattern and not pattern.match(filename):
                report.warn(rel, f"Name does not follow the {name}/ convention: {spec.get('naming', '')}")

    loose = set(base.get("loose_root_extensions") or [])
    for rel in files:
        if "/" not in rel and rel.rsplit(".", 1)[-1].lower() in loose:
            report.warn(rel, "Loose file at the repository root. Move it into a folder of the layout.")


def check_required(repo: Path, files: list[str], config: dict, profile: dict, resolved: dict, report: Report) -> None:
    required = list(base_config()["required_files"]) + list(profile.get("required_files") or [])
    required += [rel[: -len(".tmpl")] if rel.endswith(".tmpl") else rel for rel in resolved["files"]]
    license_key = str(config.get("license", "none"))
    if license_key.lower() != "none":
        required.append("LICENSE")
    for name, spec in resolved["folders"].items():
        if spec.get("license") and any(f.startswith(f"{name}/") for f in files):
            required.append(f"{name}/LICENSE")
    for rel in dict.fromkeys(required):
        if not (repo / rel).exists():
            report.error(rel, "Required file is missing. Run init --existing to add it.")
    if os.environ.get("REPO_PRIVATE") == "false" and license_key.lower() == "none":
        report.error("LICENSE", "Public repository without a license. Set license in .standard.yml and run init --existing.")


def check_generated(repo: Path, config: dict, report: Report) -> None:
    base = base_config()
    try:
        expected = build_instruction_files(repo, config)
    except StandardError as error:
        report.error(".standard.yml", str(error))
        return
    for rel, content in expected.items():
        path = repo / rel
        if not path.exists():
            report.error(rel, "Missing. Run agents.")
            continue
        actual = path.read_text(encoding="utf-8")
        if tidy(without_marked_blocks(actual)) == tidy(without_marked_blocks(content)):
            continue
        version = GENERATED_VERSION.search(actual)
        if rel.endswith("AGENTS.md") and version and version["version"] != base["version"]:
            report.warn(rel, f"Generated with standard {version['version']}, current is {base['version']}. Run agents.")
        else:
            report.error(rel, "Out of date with .standard.yml or docs/goals.md, or edited by hand. Run agents.")
    agents = repo / "AGENTS.md"
    if agents.exists():
        count = len(agents.read_text(encoding="utf-8").splitlines())
        if count > base["max_agents_lines"]:
            report.error("AGENTS.md", f"{count} lines. Keep it under {base['max_agents_lines']}.")
    gemini = repo / ".gemini" / "settings.json"
    if gemini.exists():
        try:
            names = json.loads(gemini.read_text(encoding="utf-8")).get("context", {}).get("fileName", [])
        except json.JSONDecodeError:
            names = []
        if "AGENTS.md" not in names:
            report.error(".gemini/settings.json", "context.fileName must include AGENTS.md so Gemini CLI reads it.")
    workflow = repo / ".github" / "workflows" / "standard.yml"
    if workflow.exists():
        standard_repo, ref = parse_standard(config.get("standard"))
        if f"{standard_repo}/.github/workflows/check.yml@{ref}" not in workflow.read_text(encoding="utf-8"):
            report.error(".github/workflows/standard.yml", f"Must call {standard_repo}/.github/workflows/check.yml@{ref}.")


def check_content(repo: Path, files: list[str], report: Report) -> None:
    base = base_config()
    banned = re.compile(r"\b(" + "|".join(re.escape(w) for w in base["banned_words"]) + r")\b", re.I)
    hosts = re.compile("|".join(re.escape(h) for h in base["placeholder_hosts"]), re.I)
    max_bytes = base["max_file_mb"] * 1024 * 1024
    lfs = lfs_patterns(repo)
    for rel in files:
        path = repo / rel
        filename = rel.rsplit("/", 1)[-1]
        size = path.stat().st_size
        if size > max_bytes and not any(fnmatch.fnmatch(rel, p) or fnmatch.fnmatch(filename, p) for p in lfs):
            report.error(rel, f"{size / 1024 / 1024:.1f} MB. Files over {base['max_file_mb']} MB go to Git LFS or external storage.")
        if filename in GENERATED_FILES or filename.startswith("LICENSE") or path.suffix.lower() not in TEXT_SUFFIXES:
            continue
        if size > 1024 * 1024:
            continue
        text = path.read_text(encoding="utf-8", errors="ignore")
        owner_items = text.count(OWNER_TODO + ":")
        if owner_items:
            report.warn(rel, f"{owner_items} TODO(owner) items for the owner to write.")
        if re.search(r"lorem ipsum", text, re.I):
            report.error(rel, "Contains lorem ipsum. Write real content or an honest, labeled placeholder.")
        if hosts.search(text):
            report.error(rel, "Uses a placeholder image service. Use a real asset or an honest, labeled placeholder.")
        for number, line in enumerate(text.splitlines(), start=1):
            if TODO_MARK.search(line) and not ISSUE_REF.search(line):
                report.warn(f"{rel}:{number}", "TODO without an issue reference. Link an issue or remove it.")
        if path.suffix.lower() == ".md":
            dashes = 0
            for number, line in prose_lines(text):
                match = banned.search(line)
                if match:
                    report.warn(f"{rel}:{number}", f"Marketing word '{match.group(0)}'. Say what it does instead.")
                dashes += line.count("\u2014")
            if dashes:
                report.warn(rel, f"{dashes} em dashes. Use periods and commas.")


def check_pull_request(report: Report) -> None:
    title = os.environ.get("PR_TITLE", "")
    body = os.environ.get("PR_BODY", "") or ""
    if not CONVENTIONAL_TITLE.match(title):
        report.error("pull request", f"Title '{title}' does not follow Conventional Commits, "
                                     "for example 'feat(api): add weather endpoint'.")
    sections = markdown_sections(body)
    for name in PR_SECTIONS:
        if name not in sections:
            report.error("pull request", f"Section '## {name}' is missing.")
        elif not sections[name].strip():
            report.error("pull request", f"Section '## {name}' is empty. Write 'None' if it does not apply.")
    task = sections.get("Task", "")
    if task and not re.search(r"#\d+|https?://|\bnone\b", task, re.I):
        report.error("pull request", "Section '## Task' must link an issue (#12) or say None.")


def run_check(repo: Path, pull_request: bool = False) -> Report:
    report = Report()
    try:
        config = read_config(repo)
    except StandardError as error:
        report.error(".standard.yml", str(error))
        return report
    result = check_config(repo, config, report)
    if result:
        profile, resolved = result
        files = list_files(repo)
        check_required(repo, files, config, profile, resolved, report)
        check_layout(files, config, profile, resolved, report)
        check_generated(repo, config, report)
        check_content(repo, files, report)
    if pull_request:
        check_pull_request(report)
    return report


# templates, packaging and selftest

def cmd_templates(out_dir: Path) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    for name in profile_names():
        target = out_dir / f"template-{name}"
        if target.exists():
            shutil.rmtree(target)
        init_repo(target, {"profile": name, "name": "CHANGE-ME"})
        print(f"Built {target}")


def cmd_package_skills(out_dir: Path) -> None:
    if out_dir.exists():
        shutil.rmtree(out_dir)
    out_dir.mkdir(parents=True)
    version = base_config()["version"]
    ignore = shutil.ignore_patterns("__pycache__", "*.pyc")

    setup_dir = out_dir / "repo-setup"
    shutil.copytree(STANDARD_ROOT / "skills" / "repo-setup", setup_dir, ignore=ignore)
    snapshot = setup_dir / "standard"
    for name in ("base", "profiles", "patterns", "prompts"):
        shutil.copytree(STANDARD_ROOT / name, snapshot / name, ignore=ignore)
    (snapshot / "scripts").mkdir()
    shutil.copy2(STANDARD_ROOT / "scripts" / "standard.py", snapshot / "scripts" / "standard.py")
    shutil.copy2(STANDARD_ROOT / "preferences.md", snapshot / "preferences.md")
    (snapshot / "VERSION").write_text(version + "\n", encoding="utf-8")

    review_dir = out_dir / "code-review"
    shutil.copytree(STANDARD_ROOT / "skills" / "code-review", review_dir, ignore=ignore)
    shutil.copytree(STANDARD_ROOT / "patterns", review_dir / "references" / "patterns", ignore=ignore)

    for folder in (setup_dir, review_dir):
        archive = shutil.make_archive(str(folder), "zip", root_dir=out_dir, base_dir=folder.name)
        print(f"Packaged {archive}")


def cmd_skills_repo(out_dir: Path) -> None:
    """Build the public skills repository in OUT/repo and its release archives in OUT/release."""
    if out_dir.exists():
        shutil.rmtree(out_dir)
    packaged = out_dir / "packaged"
    cmd_package_skills(packaged)
    version = base_config()["version"]
    repo = out_dir / "repo"
    release = out_dir / "release"
    (repo / "skills").mkdir(parents=True)
    release.mkdir()
    for name in ("repo-setup", "code-review"):
        shutil.copytree(packaged / name, repo / "skills" / name)
        shutil.copy2(packaged / f"{name}.zip", release / f"{name}.zip")
    readme = (STANDARD_ROOT / "skills" / "published-readme.md.tmpl").read_text(encoding="utf-8")
    (repo / "README.md").write_text(render(readme, {"version": version}), encoding="utf-8")
    shutil.copy2(STANDARD_ROOT / "LICENSE", repo / "LICENSE")
    (repo / ".gitattributes").write_text("* text=auto eol=lf\n", encoding="utf-8")
    (out_dir / "VERSION").write_text(version + "\n", encoding="utf-8")
    print(f"Built skills repository {version} in {repo}")


def git_add_all(repo: Path) -> None:
    subprocess.run(["git", "init", "-q"], cwd=repo, check=True)
    subprocess.run(["git", "add", "-A"], cwd=repo, check=True)


def cmd_selftest() -> int:
    failures: list[str] = []
    cases = [(name, {}, {}) for name in profile_names()]
    cases += [
        ("web", {"three_d": "core", "flows": "multi-step", "build": "npm", "motion": "rich"}, {"api": "software"}),
        ("data-ai", {"kind": "ml", "personal_data": "present", "platform": "databricks"}, {}),
        ("hardware", {"firmware": "none", "mechanical": "cad", "power": "battery"}, {"app": "software"}),
        ("docs", {"format": "typst", "citation": "none"}, {}),
    ]
    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp)
        first_repo = None
        for index, (profile, options, parts) in enumerate(cases):
            repo = root / f"case-{index}-{profile}"
            init_repo(repo, {"profile": profile, "name": repo.name, "options": options,
                             "parts": parts, "setup_done": True, "content_language": "es"})
            git_add_all(repo)
            report = run_check(repo)
            lines = len((repo / "AGENTS.md").read_text(encoding="utf-8").splitlines())
            print(f"{repo.name}: {len(report.errors)} errors, {len(report.warnings)} warnings, AGENTS.md {lines} lines")
            if report.errors:
                failures.append(f"{repo.name}: {report.errors}")
            first_repo = first_repo or repo

        def expect_error(label: str, fragment: str, pull_request: bool = False) -> None:
            report = run_check(first_repo, pull_request=pull_request)
            if not any(fragment in message for _, message in report.errors):
                failures.append(f"{label}: expected an error containing '{fragment}'")
            else:
                print(f"negative case passed: {label}")

        stray = first_repo / "stray"
        stray.mkdir()
        (stray / "notes.txt").write_text("x\n", encoding="utf-8")
        git_add_all(first_repo)
        expect_error("undeclared folder", "not declared")
        shutil.rmtree(stray)

        agents = first_repo / "AGENTS.md"
        original = agents.read_text(encoding="utf-8")
        agents.write_text(original + "\nExtra rule written by hand.\n", encoding="utf-8")
        expect_error("hand-edited AGENTS.md", "edited by hand")
        agents.write_text(original + "\n<!-- antislop:start -->\n## antislop\nPointer.\n<!-- antislop:end -->\n",
                          encoding="utf-8")
        if run_check(first_repo).errors:
            failures.append("a block owned by another installer should not count as a hand edit")
        else:
            print("negative case passed: foreign marked block is kept")
        agents.write_text(original, encoding="utf-8")

        readme = next(first_repo.glob("*/README.md"))
        readme_text = readme.read_text(encoding="utf-8")
        readme.write_text(readme_text + "\nLorem ipsum dolor sit amet.\n", encoding="utf-8")
        expect_error("lorem ipsum", "lorem ipsum")
        readme.write_text(readme_text, encoding="utf-8")

        os.environ["PR_TITLE"], os.environ["PR_BODY"] = "update files", "## Task\n\nCloses #\n"
        expect_error("pull request title", "Conventional Commits", pull_request=True)
        expect_error("pull request sections", "is missing", pull_request=True)
        good_body = "\n\n".join(f"## {name}\n\n" + ("Closes #3" if name == "Task" else "None") for name in PR_SECTIONS)
        os.environ["PR_TITLE"], os.environ["PR_BODY"] = "feat(api): add weather endpoint", good_body
        if run_check(first_repo, pull_request=True).errors:
            failures.append("a complete pull request should pass")
        else:
            print("positive case passed: complete pull request")

        goals = first_repo / "docs" / "goals.md"
        goals.write_text(goals.read_text(encoding="utf-8").replace(
            "TODO(owner): One sentence. What this repository exists to achieve.", "Show live air quality for my city."),
            encoding="utf-8")
        expect_error("goals changed without regenerating", "Out of date")
        write_instruction_files(first_repo, read_config(first_repo))
        if "Show live air quality" not in agents.read_text(encoding="utf-8"):
            failures.append("goal summary did not reach AGENTS.md")
        else:
            print("positive case passed: goal summary reaches AGENTS.md")

        skills_out = root / "skills-out"
        cmd_skills_repo(skills_out)
        expected = ["repo/README.md", "repo/skills/repo-setup/SKILL.md", "repo/skills/repo-setup/standard/VERSION",
                    "repo/skills/code-review/SKILL.md", "release/repo-setup.zip", "release/code-review.zip"]
        missing = [rel for rel in expected if not (skills_out / rel).exists()]
        if missing:
            failures.append(f"skills-repo is missing {missing}")
        else:
            print("positive case passed: skills repository")

        existing = root / "existing"
        existing.mkdir()
        (existing / "README.md").write_text("# Mine\n", encoding="utf-8")
        (existing / ".gitignore").write_text("secret.txt\n", encoding="utf-8")
        init_repo(existing, {"profile": "software", "existing": True})
        if (existing / "README.md").read_text(encoding="utf-8") != "# Mine\n":
            failures.append("init --existing overwrote README.md")
        elif "secret.txt" not in (existing / ".gitignore").read_text(encoding="utf-8"):
            failures.append("init --existing dropped .gitignore lines")
        else:
            print("positive case passed: init --existing keeps existing files")

    if failures:
        print("\nSELFTEST FAILED")
        for failure in failures:
            print(f"- {failure}")
        return 1
    print("\nselftest passed")
    return 0


# CLI

def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    commands = parser.add_subparsers(dest="command", required=True)

    init = commands.add_parser("init", help="create a repository or add missing files")
    init.add_argument("path")
    init.add_argument("--profile", choices=profile_names())
    init.add_argument("--name")
    init.add_argument("--owner")
    init.add_argument("--license", help="MIT, Apache-2.0, GPL-3.0, CERN-OHL-P-2.0, CC-BY-4.0 or none")
    init.add_argument("--standard", help="for example SVN11X/standards@v1")
    init.add_argument("--content-language", help="language code of user-facing content, for example es")
    init.add_argument("--option", action="append", metavar="KEY=VALUE")
    init.add_argument("--part", action="append", metavar="FOLDER=PROFILE")
    init.add_argument("--part-option", action="append", metavar="FOLDER.KEY=VALUE")
    init.add_argument("--existing", action="store_true", help="the repository already exists")
    init.add_argument("--interactive", action="store_true", help="ask the setup questions")
    init.add_argument("--setup-done", action="store_true", help="the owner answered the setup questions")

    agents = commands.add_parser("agents", help="regenerate AGENTS.md and CLAUDE.md")
    agents.add_argument("path")

    check = commands.add_parser("check", help="check a repository")
    check.add_argument("path")
    check.add_argument("--pr", action="store_true", help="also check PR_TITLE and PR_BODY")

    templates = commands.add_parser("templates", help="build template repositories")
    templates.add_argument("out_dir")

    package = commands.add_parser("package-skills", help="bundle the skills")
    package.add_argument("out_dir")

    skills_repo = commands.add_parser("skills-repo", help="build the public skills repository")
    skills_repo.add_argument("out_dir")

    commands.add_parser("selftest", help="run every profile through init and check")

    args = parser.parse_args(argv)
    try:
        if args.command == "init":
            created = init_repo(Path(args.path), {
                "profile": args.profile, "name": args.name, "owner": args.owner, "license": args.license,
                "standard": args.standard, "content_language": args.content_language,
                "options": parse_pairs(args.option), "parts": parse_pairs(args.part),
                "part_options": parse_pairs(args.part_option), "existing": args.existing,
                "interactive": args.interactive, "setup_done": args.setup_done,
            })
            print("\n".join(f"created {rel}" for rel in created) or "Nothing to add.")
            print("\nNext: write docs/goals.md (and DESIGN.md for web), then run agents and check.")
            return 0
        if args.command == "agents":
            repo = Path(args.path).resolve()
            written = write_instruction_files(repo, read_config(repo))
            print("\n".join(f"updated {rel}" for rel in written) or "Already up to date.")
            return 0
        if args.command == "check":
            return run_check(Path(args.path).resolve(), pull_request=args.pr).print()
        if args.command == "templates":
            cmd_templates(Path(args.out_dir).resolve())
            return 0
        if args.command == "package-skills":
            cmd_package_skills(Path(args.out_dir).resolve())
            return 0
        if args.command == "skills-repo":
            cmd_skills_repo(Path(args.out_dir).resolve())
            return 0
        if args.command == "selftest":
            return cmd_selftest()
    except StandardError as error:
        print(f"error: {error}", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
