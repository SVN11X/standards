def root_file_patterns(resolved: dict) -> list[str]:
    return list(base_config().get("root_files") or []) + list(resolved.get("root_files") or [])


def always_folders() -> set[str]:
    return set(base_config().get("always_folders") or ["docs"])


def kebab(filename: str) -> str:
    stem, dot, suffix = filename.rpartition(".")
    if not dot:
        stem, suffix = filename, ""
    stem = re.sub(r"[^a-z0-9]+", "-", stem.lower()).strip("-") or "file"
    return stem + ("." + suffix.lower() if suffix else "")


def snake(filename: str) -> str:
    stem, _, suffix = filename.rpartition(".")
    stem = re.sub(r"[^a-z0-9]+", "_", stem.lower()).strip("_") or "module"
    return f"{stem}.{suffix.lower()}"


def looks_secret(filename: str) -> bool:
    """True for names that usually hold credentials or sessions, such as .env, *.pem or cookies.txt."""
    return bool(SECRET_NAME.match(filename.lower()))


def root_file_target(filename: str, available: set[str]) -> tuple[str | None, str]:
    lowered = filename.lower()
    suffix = Path(lowered).suffix
    if suffix == ".py":
        if lowered.startswith("test_") or lowered.endswith("_test.py"):
            candidates, reason = ["tests"], "Test module."
        elif lowered.startswith(("bootstrap", "install")):
            candidates, reason = ["scripts", "src"], "Setup script for developers."
        else:
            candidates, reason = ["src"], "Python source code."
        for folder in candidates:
            if folder in available:
                return f"{folder}/{snake(filename)}", reason
        return None, "No folder for Python code in this profile. Choose a destination."
    for suffixes, candidates in SUFFIX_TARGETS:
        if suffix in suffixes:
            for folder in candidates:
                if folder in available:
                    return f"{folder}/{kebab(filename)}", f"{suffix} files belong in {folder}/."
            return None, f"No folder for {suffix} files in this profile. Choose a destination or declare an extra folder."
    return None, "Unknown file type. Choose a destination."


def plan_migration(repo: Path, profile_name: str, answers: dict) -> dict:
    """Propose where every misplaced file should go. Nothing is moved here."""
    profile = load_profile(profile_name)
    resolved = resolve(profile, answers)
    if resolved["problems"]:
        raise StandardError(" ".join(resolved["problems"]))
    folders = resolved["folders"]
    available = set(folders) | always_folders()
    root_patterns = root_file_patterns(resolved)
    hidden_allowed = set(base_config().get("hidden_folders") or [])
    files = list_files(repo)
    moves, decide, flagged_dirs = [], [], set()

    for rel in files:
        parts = rel.split("/")
        filename = parts[-1]
        if looks_secret(filename):
            decide.append({"path": rel, "light": "red",
                           "reason": "Looks like a secret or a session file. Remove it from git (git rm --cached), "
                                     "add it to .gitignore and rotate the secret. Do not move it."})
            continue
        if len(parts) == 1:
            if filename.startswith(".") or any(fnmatch.fnmatchcase(filename, p) for p in root_patterns):
                continue
            target, reason = root_file_target(filename, available)
            if target:
                moves.append({"from": rel, "to": target, "reason": reason})
            else:
                decide.append({"path": rel, "light": "yellow", "reason": reason})
            continue
        top = parts[0]
        if top in folders or top in always_folders() or top in hidden_allowed:
            continue
        alias = DIR_ALIASES.get(top.lower())
        if not top.startswith(".") and alias and alias.split("/")[0] in available:
            moves.append({"from": rel, "to": "/".join([alias] + parts[1:]),
                          "reason": f"{top}/ is {alias}/ in the {profile['name']} profile."})
            continue
        if top in flagged_dirs:
            continue
        flagged_dirs.add(top)
        tokens = set(re.split(r"[^a-z0-9]+", top.lower()))
        if top.startswith("."):
            reason = ("Hidden folder not allowed by the standard. Move tools into scripts/, add it to .gitignore if it "
                      "is local state, or declare it in .standard.yml under extra_folders with a reason.")
        elif tokens & GENERATED_HINTS:
            reason = ("Looks like generated output. Add it to .gitignore and remove it from git (git rm -r --cached), "
                      "or keep only small real examples in tests/fixtures/ or docs/examples/.")
        else:
            reason = (f"Folder is not part of the {profile['name']} layout. Choose a destination, or declare it in "
                      ".standard.yml under extra_folders with a reason.")
        decide.append({"path": f"{top}/", "light": "yellow", "reason": reason})

    moving_away = {move["from"] for move in moves}
    targets: dict[str, int] = {}
    for move in moves:
        targets[move["to"]] = targets.get(move["to"], 0) + 1
    kept = []
    for move in moves:
        clash = targets[move["to"]] > 1 or ((repo / move["to"]).exists() and move["to"] not in moving_away)
        if clash:
            decide.append({"path": move["from"], "light": "yellow",
                           "reason": f"Destination {move['to']} is already taken. Choose another name."})
        else:
            kept.append(move)
    add_references(repo, files, kept)
    return {"profile": profile["name"], "options": {k: as_text(v) for k, v in answers.items()},
            "moves": kept, "decide": decide}


def add_references(repo: Path, files: list[str], moves: list[dict]) -> None:
    """List the lines that mention a moved file, so paths and imports can be fixed after the move."""
    new_path = {move["from"]: move["to"] for move in moves}
    texts = {}
    for rel in files:
        path = repo / rel
        if path.suffix.lower() in REFERENCE_SUFFIXES and path.stat().st_size < 1024 * 1024:
            texts[rel] = path.read_text(encoding="utf-8", errors="ignore").splitlines()
    for move in moves:
        old_name = move["from"].rsplit("/", 1)[-1]
        module = re.compile(rf"\b(?:import|from)\s+{re.escape(Path(old_name).stem)}\b") if old_name.endswith(".py") else None
        same_folder = move["to"].rsplit("/", 1)[0]
        found = []
        for rel, lines in texts.items():
            if rel == move["from"]:
                continue
            shown = new_path.get(rel, rel)
            for number, line in enumerate(lines, start=1):
                by_name = old_name in line
                by_import = bool(module and module.search(line)) and shown.rsplit("/", 1)[0] != same_folder
                if by_name or by_import:
                    found.append(f"{shown}:{number}")
        if found:
            move["references"] = found[:20]


def write_plan(repo: Path, plan: dict) -> Path:
    path = repo / PLAN_PATH
    path.parent.mkdir(parents=True, exist_ok=True)
    header = (f"# Migration plan generated by {DEFAULT_REPO} {base_config()['version']}. Nothing has moved yet.\n"
              "# 1. Review every move. Edit 'to' to rename, for example to translate a name to English.\n"
              "# 2. Resolve every item under 'decide' by hand. The check fails until they are resolved.\n"
              "# 3. Apply: python <standards>/scripts/standard.py migrate . --apply\n"
              "# 4. Fix every line listed under 'references', then run agents and check.\n")
    body = yaml.safe_dump(plan, sort_keys=False, allow_unicode=True, width=120)
    write_text(path, header + body)
    return path


def remove_empty_parents(path: Path, stop: Path) -> None:
    parent = path.parent
    while parent != stop and parent.exists() and not any(parent.iterdir()):
        parent.rmdir()
        parent = parent.parent


def apply_migration(repo: Path) -> tuple[list[str], list[str]]:
    plan_file = repo / PLAN_PATH
    if not plan_file.exists():
        raise StandardError(f"No plan at {PLAN_PATH}. Run migrate without --apply first.")
    if not (repo / ".git").exists():
        raise StandardError("migrate --apply needs a git repository, so every moved file keeps its history.")
    plan = load_yaml(plan_file)
    moved = []
    for move in plan.get("moves") or []:
        source, target = repo / move["from"], repo / move["to"]
        if not source.exists():
            continue
        if target.exists():
            raise StandardError(f"{move['to']} already exists. Edit the plan and run --apply again.")
        target.parent.mkdir(parents=True, exist_ok=True)
        result = subprocess.run(["git", "mv", "--", move["from"], move["to"]], cwd=repo, capture_output=True, text=True)
        if result.returncode != 0:
            shutil.move(str(source), str(target))
        remove_empty_parents(source, repo)
        moved.append(f"{move['from']} -> {move['to']}")
    created = init_repo(repo, {"profile": plan["profile"], "options": plan.get("options") or {}, "existing": True})
    return moved, created


# GitHub settings

def repository_settings() -> dict:
    return load_yaml(STANDARD_ROOT / "settings" / "repository.yml")


def github_slug(repo: Path, explicit: str | None) -> str:
    if explicit:
        return explicit
    try:
        url = subprocess.run(["git", "remote", "get-url", "origin"], cwd=repo, capture_output=True,
                             text=True, check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        raise StandardError("No git remote named origin. Pass --repo OWNER/NAME.")
    match = re.search(r"github\.com[:/]([^/]+)/(.+?)(?:\.git)?$", url)
    if not match:
        raise StandardError(f"origin is not a GitHub URL: {url}. Pass --repo OWNER/NAME.")
    return f"{match[1]}/{match[2]}"


def github_commands(config: dict, slug: str, prune_labels: list[str] | None = None) -> list[tuple[str, list[str], str | None]]:
    """Every gh call that brings a repository to the standard, as (label, arguments, JSON input)."""
    settings = repository_settings()
    about = config.get("github") or {}
    features = {**settings["features"], **(about.get("features") or {})}
    merge = settings["merge"]
    flag = lambda value: "true" if value else "false"
    commands = [("About and features", ["repo", "edit", slug,
                 "--description", about.get("description", ""), "--homepage", about.get("homepage", ""),
                 f"--enable-issues={flag(features['has_issues'])}", f"--enable-projects={flag(features['has_projects'])}",
                 f"--enable-wiki={flag(features['has_wiki'])}", f"--enable-discussions={flag(features['has_discussions'])}",
                 f"--enable-squash-merge={flag(merge['allow_squash_merge'])}",
                 f"--enable-merge-commit={flag(merge['allow_merge_commit'])}",
                 f"--enable-rebase-merge={flag(merge['allow_rebase_merge'])}",
                 f"--delete-branch-on-merge={flag(merge['delete_branch_on_merge'])}"], None),
                ("Topics", ["api", "--method", "PUT", f"repos/{slug}/topics", "--input", "-"],
                 json.dumps({"names": list(about.get("topics") or [])})),
                ("Squash commit message", ["api", "--method", "PATCH", f"repos/{slug}", "--input", "-"],
                 json.dumps({"squash_merge_commit_title": merge["squash_merge_commit_title"],
                             "squash_merge_commit_message": merge["squash_merge_commit_message"]}))]
    security = settings["security"]
    if security.get("vulnerability_alerts"):
        commands.append(("Dependabot alerts", ["api", "--method", "PUT", f"repos/{slug}/vulnerability-alerts"], None))
    if security.get("automated_security_fixes"):
        commands.append(("Dependabot security updates", ["api", "--method", "PUT", f"repos/{slug}/automated-security-fixes"], None))
    if security.get("private_vulnerability_reporting"):
        commands.append(("Private vulnerability reporting", ["api", "--method", "PUT", f"repos/{slug}/private-vulnerability-reporting"], None))
    if security.get("secret_scanning"):
        analysis = {"secret_scanning": {"status": "enabled"}}
        if security.get("secret_scanning_push_protection"):
            analysis["secret_scanning_push_protection"] = {"status": "enabled"}
        commands.append(("Secret scanning", ["api", "--method", "PATCH", f"repos/{slug}", "--input", "-"],
                         json.dumps({"security_and_analysis": analysis})))
    if security.get("code_scanning_default_setup"):
        commands.append(("Code scanning", ["api", "--method", "PATCH", f"repos/{slug}/code-scanning/default-setup",
                                           "--input", "-"], json.dumps({"state": "configured"})))
    for label in settings["labels"]:
        commands.append((f"Label {label['name']}", ["label", "create", label["name"], "--repo", slug, "--color",
                                                   label["color"], "--description", label["description"], "--force"], None))
    for name in prune_labels or []:
        commands.append((f"Remove label {name}", ["label", "delete", name, "--repo", slug, "--yes"], None))
    return commands


def run_gh(arguments: list[str], payload: str | None) -> tuple[bool, str]:
    try:
        result = subprocess.run(["gh", *arguments], input=payload, capture_output=True, text=True)
    except OSError:
        raise StandardError("The GitHub CLI (gh) is not installed or not in PATH.")
    lines = (result.stderr or result.stdout).strip().splitlines()
    return result.returncode == 0, lines[-1] if lines else ""


def labels_to_prune(slug: str) -> list[str]:
    try:
        result = subprocess.run(["gh", "label", "list", "--repo", slug, "--limit", "200", "--json", "name",
                                 "--jq", ".[].name"], capture_output=True, text=True)
    except OSError:
        raise StandardError("The GitHub CLI (gh) is not installed or not in PATH.")
    if result.returncode != 0:
        return []
    keep = {label["name"] for label in repository_settings()["labels"]}
    return [name for name in result.stdout.splitlines() if name and name not in keep]


def apply_ruleset(slug: str) -> tuple[bool, str]:
    path = STANDARD_ROOT / "settings" / "ruleset-main.json"
    name = json.loads(path.read_text(encoding="utf-8"))["name"]
    listing = subprocess.run(["gh", "api", f"repos/{slug}/rulesets"], capture_output=True, text=True)
    if listing.returncode != 0:
        return False, "could not read rulesets. Private repositories need GitHub Pro for rulesets."
    existing = next((item for item in json.loads(listing.stdout or "[]") if item.get("name") == name), None)
    method, endpoint = ("PUT", f"repos/{slug}/rulesets/{existing['id']}") if existing else ("POST", f"repos/{slug}/rulesets")
    return run_gh(["api", "--method", method, endpoint, "--input", "-"], path.read_text(encoding="utf-8"))


def cmd_github(repo: Path, slug_arg: str | None, apply: bool, prune: bool, protect: bool) -> int:
    config = read_config(repo)
    slug = github_slug(repo, slug_arg)
    if not (config.get("github") or {}).get("description"):
        raise StandardError("Write github.description in .standard.yml first. It is the text of the About panel.")
    prune_list = labels_to_prune(slug) if (apply and prune) else []
    commands = github_commands(config, slug, prune_list)
    if not apply:
        for label, arguments, payload in commands:
            print(f"{label}: gh {' '.join(arguments)}" + (f" <<< {payload}" if payload else ""))
        print("\nDry run. Add --apply to change the repository on GitHub." + (" Add --protect for the branch ruleset." if not protect else ""))
        return 0
    failures = 0
    for label, arguments, payload in commands:
        ok, message = run_gh(arguments, payload)
        print(f"{'ok  ' if ok else 'skip'} {label}" + ("" if ok else f": {message}"))
        failures += 0 if ok else 1
    if protect:
        ok, message = apply_ruleset(slug)
        print(f"{'ok  ' if ok else 'skip'} Branch ruleset" + ("" if ok else f": {message}"))
        failures += 0 if ok else 1
    print("\nNot available through the API, set them by hand once: the social preview image (Settings), "
          "and which sections the home page shows (the gear next to About: Releases, Packages, Deployments).")
    if failures:
        print(f"{failures} settings were skipped. Some need a public repository or a paid plan.")
    return 0


def changelog_notes(repo: Path, version: str) -> str:
    path = repo / "CHANGELOG.md"
    if path.exists():
        text = path.read_text(encoding="utf-8")
        match = re.search(rf"^## \[{re.escape(version)}\][^\n]*\n(.*?)(?=^## \[|\Z)", text, re.S | re.M)
        if match and match.group(1).strip():
            return match.group(1).strip() + "\n"
    return f"Release {version}. See the commit history for details.\n"


def check_github(config: dict, report: Report) -> None:
    about = config.get("github") or {}
    description = (about.get("description") or "").strip()
    if not description:
        message = "Write github.description in .standard.yml: one sentence for the About panel."
        if config.get("setup") == "done":
            report.error(".standard.yml", message)
        else:
            report.warn(".standard.yml", message)
    if os.environ.get("GITHUB_ACTIONS") != "true":
        return
    live = {"description": os.environ.get("REPO_DESCRIPTION", "").strip(),
            "homepage": os.environ.get("REPO_HOMEPAGE", "").strip(),
            "topics": sorted(t for t in os.environ.get("REPO_TOPICS", "").split(",") if t)}
    wanted = {"description": description, "homepage": (about.get("homepage") or "").strip(),
              "topics": sorted(about.get("topics") or [])}
    different = [key for key in wanted if wanted[key] != live[key]]
    if different:
        report.warn(".standard.yml", f"The About panel on GitHub differs in {', '.join(different)}. "
                                     "Run: python .standards/scripts/standard.py github . --apply")


